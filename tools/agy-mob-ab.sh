#!/usr/bin/env bash
# 怪人「カクシン様」の新旧2版を agy に**強制A/B**で比べさせる。
# **順序を入れ替えて2回**回し、両方の判定を並べて出す。
#
#   bash tools/agy-mob-ab.sh [旧版のディレクトリ] [新版のディレクトリ]
#                            # 既定 C:/tmp/prev2  C:/tmp/ev
#   bash tools/agy-mob-ab.sh --once <A> <B>       # 1回だけ（デバッグ用。判定には使わない）
#
# 直そうとする前に、いまの版を旧側へ退避しておく:
#   rm -rf C:/tmp/prev2 && cp -r C:/tmp/ev C:/tmp/prev2
#
# 【なぜ2回回すのか — v26末に判明した位置バイアス】
# この台本は元は1回しか回さず、常に「A＝旧版 / B＝新版」で並べていた。
# その順序で **16回連続、3角度すべて＋総合で B（＝新版）が勝った**。改善の証拠に見える。
# ところが順序を入れ替えて（A に新版、B に旧版）回すと、
# 評価者は3角度すべてと総合で **B＝旧版** を選んだ。
# しかも B を選んだ理由として「B は腰の紐でエプロンが体に絞られている」と書いている。
# **腰の紐が見えるのは新版（このとき A 側）だけ**で、旧版には無い。
# つまり評価者は**位置 B を選んだうえで、A の内容を根拠として作文していた**。
#
# したがって:
#   ・1回の判定は無意味。**順序を入れ替えた2回で同じ版が勝ったときだけ**「差がある」と見なす。
#   ・2回が割れたら「差は検出できなかった」であって、引き分けでも新版の勝ちでもない。
#   ・理由の本文は両方の回で当てにならない。作業リストにしない。
#
# 位置に依存しない指標（こちらを主に使うこと）:
#   tools/silhouette-diff.mjs / silhouette-overlay.mjs … 参照画との輪郭の実測
#   tools/mob-bbox.mjs                                  … 全体・メッシュごとの外接箱
#   自分の目で参照画と並べる                              … 結局これがいちばん強い
set -eu

ONCE=0
if [ "${1:-}" = "--once" ]; then ONCE=1; shift; fi
A="${1:-C:/tmp/prev2}"
B="${2:-C:/tmp/ev}"
REF="$(cd "$(dirname "$0")/../docs/mobref" && pwd -W 2>/dev/null || cd "$(dirname "$0")/../docs/mobref" && pwd)"
AGY="$LOCALAPPDATA/agy/bin/agy.exe"

ask() {   # ask <左に置くディレクトリ> <右に置くディレクトリ>
  "$AGY" --model gemini-3.1-pro-high --effort high --dangerously-skip-permissions \
    --print-timeout 12m --add-dir "$1" --add-dir "$2" --add-dir "$REF" -p "同じ3Dキャラクターの、2つのバージョンのレンダリングがある。どちらがコンセプトアートの再現としてより近いかを判定してほしい。

コンセプトアート（目標）: $REF/concept4.png

版A
  正面: $1/yaw0.png
  斜め前（片側）: $1/yaw55.png
  斜め前（反対側）: $1/yaw-55.png

版B
  正面: $2/yaw0.png
  斜め前（片側）: $2/yaw55.png
  斜め前（反対側）: $2/yaw-55.png

角度ごとに、AとBのどちらがコンセプトアートに近いかを選び、その理由を述べてほしい。最後に総合でどちらが近いかを1つ選ぶこと。引き分けは選ばないこと。
そのうえで、勝ったほうの版に**まだ残っている**差を、重要な順に挙げてほしい。数値ではなく見たままの言葉で。

どちらが新しい版かという情報は与えない。純粋に画だけで判断すること。"
}

echo "########## 第1回: A=$A / B=$B ##########"
ask "$A" "$B"

if [ "$ONCE" = "1" ]; then exit 0; fi

echo
echo "########## 第2回（順序を入れ替え）: A=$B / B=$A ##########"
echo "※ 第1回で '版B'、第2回で '版A' が勝てば ―― どちらも $B の勝ち。"
echo "   第1回・第2回とも '版B' が勝ったなら、それは**位置バイアス**であって差ではない。"
ask "$B" "$A"
